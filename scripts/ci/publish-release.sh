#!/usr/bin/env bash
# Publish the release payload, or reconcile an existing release with it.
#
# Three states, and only one of them is allowed to change published bytes:
#
#   no release yet          create it with every asset
#   release exists          upload only the assets it is missing; leave the rest
#                           alone and rewrite the notes
#   an asset differs        refuse, list it, and exit 1 unless FORCE_ASSETS is
#                           an explicit yes
#
# `FORCE_ASSETS` is the `force_assets` dispatch input, which is a checkbox and
# therefore arrives as `true` or `false`, but a hand-typed value reaches this
# script on a re-run or from a caller, and a typo must not quietly mean "no":
# `ture` is an error, not a refusal.
#
# The last rule is the one that matters to anything downstream: a `.node` file
# or a wasm module that someone has pinned by SHA-256 must not change because a
# workflow was re-run. Installing is fail-closed on a hash mismatch, so a silent
# re-upload turns "re-ran CI" into "broke every pinned installer". Replacing a
# published asset has to be asked for.
#
# Usage: publish-release.sh TAG NOTES_FILE ASSETS_DIR
#
#   TAG         the tag the release belongs to (already validated by the caller)
#   NOTES_FILE  release notes to write, generated by release-notes.sh
#   ASSETS_DIR  the collected payload from collect-release-assets.sh
#
# Environment:
#   GITHUB_REPOSITORY  owner/name, provided by the runner
#   GITHUB_TOKEN       provided by the runner (env `GH_TOKEN` also works)
#   FORCE_ASSETS       yes/no for replacing assets that differ from the
#                      published ones; anything else is an error
set -euo pipefail

fail() {
  if [ -n "${GITHUB_ACTIONS:-}" ]; then
    printf '::error::%s\n' "$*"
  else
    printf '!! %s\n' "$*" >&2
  fi
  exit 1
}

usage='usage: publish-release.sh TAG NOTES_FILE ASSETS_DIR'
tag=${1:?$usage}
notes=${2:?$usage}

case "${FORCE_ASSETS:-false}" in
  true | True | TRUE | yes | 1) force=true ;;
  false | False | FALSE | no | 0 | '') force=false ;;
  *) fail "FORCE_ASSETS must be true or false, got '$FORCE_ASSETS'" ;;
esac
dir=${3:?$usage}

: "${GITHUB_REPOSITORY:?GITHUB_REPOSITORY must be set (the workflow provides it)}"
command -v gh >/dev/null 2>&1 || fail 'gh is not on PATH'
[ -f "$notes" ] || fail "notes file not found: $notes"
[ -d "$dir" ] || fail "assets directory not found: $dir"

shopt -s nullglob
assets=("$dir"/*)
[ "${#assets[@]}" -gt 0 ] || fail "no assets in $dir"

# `--verify-tag` stops a release from being created off a typo'd ref: the tag
# has to exist on the remote, which the caller resolved earlier.
if ! gh release view "$tag" >/dev/null 2>&1; then
  gh release create "$tag" "${assets[@]}" \
    --title "$tag" \
    --notes-file "$notes" \
    --verify-tag
  echo "created $tag with ${#assets[@]} assets"
  exit 0
fi

digests=$(gh api "repos/$GITHUB_REPOSITORY/releases/tags/$tag" \
  --jq '.assets[] | [.name, (.digest // "")] | @tsv') ||
  fail "cannot read published assets of $tag"
declare -A published=()
while IFS=$'\t' read -r name digest; do
  [ -n "$name" ] && published["$name"]=$digest
done <<<"$digests"

missing=()
conflicts=()
unchanged=0
for path in "${assets[@]}"; do
  name=$(basename "$path")
  sum=$(sha256sum -- "$path" | cut -d' ' -f1)
  if [ -z "${published[$name]+set}" ]; then
    missing+=("$path")
  elif [ -z "${published[$name]}" ]; then
    # The release carries the asset but no digest, so there is nothing to
    # compare against. Treat it as a conflict rather than pretend it matches.
    conflicts+=("$name (no published digest)")
  elif [ "${published[$name]}" = "$sum" ]; then
    unchanged=$((unchanged + 1))
  elif [ "$force" = true ]; then
    missing+=("$path")
  else
    conflicts+=("$name")
  fi
done

if [ "${#conflicts[@]}" -gt 0 ]; then
  fail "refusing to replace published assets of $tag: ${conflicts[*]}" \
    'dispatch again with force_assets checked if replacing them is what you mean'
fi

gh release edit "$tag" --notes-file "$notes"
if [ "${#missing[@]}" -gt 0 ]; then
  gh release upload "$tag" "${missing[@]}" --clobber
fi
echo "reconciled $tag: $unchanged unchanged, ${#missing[@]} uploaded"